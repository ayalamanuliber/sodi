import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const projectRoot = process.cwd();
const outputPath = resolve(projectRoot, "docs/editorial-system/sodi-editorial-release.json");
const generatedModulePath = resolve(projectRoot, "src/lib/content-release/editorial-release.generated.ts");

const releaseSources = [
  ["sodi-content-sodi-010-v1", "/blog/costo-total-erp-pyme-argentina", "content/costo-total-erp-pyme-argentina.json"],
  ["sodi-content-sodi-012-v1", "/plantillas/presupuesto-servicios-digitales", "content/templates/presupuesto-servicios-digitales.json"],
  ["sodi-content-sodi-019-v1", "/plantillas/checklist-conciliacion-pagos-ecommerce", "content/templates/checklist-conciliacion-pagos-ecommerce.json"],
  ["sodi-content-sodi-045-v1", "/blog/hot-sale-2026-ecommerce-argentina", "content/hot-sale-2026-ecommerce-argentina.json"],
  ["sodi-content-sodi-058-v1", "/blog/whatsapp-manual-vs-bot-automatico", "content/whatsapp-manual-vs-bot-automatico.json"],
  ["sodi-content-sodi-059-v1", "/blog/como-hacer-aparecer-negocio-google-maps", "content/como-hacer-aparecer-negocio-google-maps.json"],
  ["sodi-content-sodi-069-v1", "/blog/pagina-web-para-inmobiliarias", "content/pagina-web-para-inmobiliarias.json"],
  ["sodi-content-sodi-086-v1", "/plantillas/dashboard-operativo-pyme", "content/templates/dashboard-operativo-pyme.json"],
  ["sodi-content-sodi-090-v1", "/blog/software-a-medida-vs-estandar", "content/software-a-medida-vs-estandar.json"],
  ["sodi-content-sodi-100-v1", "/blog/agencia-web-vs-freelancer", "content/agencia-web-vs-freelancer.json"],
];

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

const routes = releaseSources.map(([packetId, route, sourcePath]) => {
  const raw = readFileSync(resolve(projectRoot, sourcePath));
  const content = JSON.parse(raw.toString("utf8"));
  const kind = route.startsWith("/blog/") ? "blog" : "template";
  if (content.editorialReview?.packetId !== packetId) throw new Error(`${packetId}: packet mismatch.`);
  if (content.editorialReview?.contentStatus !== "ready_editorial") throw new Error(`${packetId}: content is not ready_editorial.`);
  if (content.editorialReview?.releaseStatus !== "approved") throw new Error(`${packetId}: release is not approved.`);

  return {
    packetId,
    route,
    kind,
    sourcePath,
    sourceFileSha256: sha256(raw),
    contentSha256: content.editorialReview.contentSha256,
    canonical: `https://sodi.com.ar${route}`,
    internalLinks: kind === "blog"
      ? (content.relatedSlugs ?? []).map((slug) => `/blog/${slug}`)
      : (content.relatedRoutes ?? []),
    ctaDestination: kind === "blog"
      ? `/diagnostico?origen=blog&articulo=${encodeURIComponent(content.slug)}&ruta=${encodeURIComponent(content.silo)}`
      : `/diagnostico?origen=plantilla&recurso=${encodeURIComponent(content.slug)}`,
    release: {
      index: true,
      follow: true,
      sitemapEligible: true,
      ownerApproved: true,
      productionAuthorized: true,
    },
  };
});

const manifest = {
  schemaVersion: 1,
  releaseId: "sodi-editorial-2026-08-31-r1",
  channel: "production_release",
  authority: "owner_authorized",
  generatedAt: "2026-08-31",
  expectedRouteCount: 10,
  routeSetSha256: sha256(routes.map((entry) => entry.route).sort().join("\n")),
  routes,
};

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(
  generatedModulePath,
  `// Generated by scripts/build-sodi-editorial-release.mjs. Do not edit by hand.\n` +
    `export const EDITORIAL_RELEASE = ${JSON.stringify(manifest, null, 2)} as const;\n`,
);

console.log(`SODI editorial release: ${routes.length}/10 routes, digest ${manifest.routeSetSha256}.`);
